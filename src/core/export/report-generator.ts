import { jsPDF } from 'jspdf';
import type { CryoDataset, AnomalyResult, UQResult, PolSARResult } from '../../types/types';

interface ReportOptions {
  dataset: CryoDataset;
  anomalies: AnomalyResult[];
  uqResults?: UQResult[];
  polsarData?: PolSARResult | null;
  radargramImageDataUrl?: string;
}

const MARGIN = 20;
const PAGE_WIDTH = 210;
const CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN;

function addHeader(doc: jsPDF, pageNum: number) {
  doc.setFontSize(7);
  doc.setTextColor(150);
  doc.text('CRYORADAR Technical Memo — CONFIDENTIAL', MARGIN, 10);
  doc.text(`Page ${pageNum}`, PAGE_WIDTH - MARGIN - 15, 10);
  doc.setDrawColor(200);
  doc.line(MARGIN, 12, PAGE_WIDTH - MARGIN, 12);
}

function addFooter(doc: jsPDF) {
  const y = 285;
  doc.setDrawColor(200);
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y);
  doc.setFontSize(7);
  doc.setTextColor(150);
  doc.text('Generated by CRYORADAR — Developer: Mehmet Gümüş (github.com/SpaceEngineerSS)', MARGIN, y + 4);
  doc.text(new Date().toISOString(), PAGE_WIDTH - MARGIN - 40, y + 4);
}

/**
 * Generates a Technical Memo PDF from current analysis state.
 * Downloads automatically via browser Blob API.
 *
 * @param options Dataset, anomalies, UQ results, PolSAR data, and optional radargram capture
 */
export function generateTechnicalMemo(options: ReportOptions): void {
  const { dataset, anomalies, uqResults, polsarData, radargramImageDataUrl } = options;
  const { metadata } = dataset;

  const doc = new jsPDF('p', 'mm', 'a4');
  let y = MARGIN;
  let page = 1;

  const ensureSpace = (needed: number) => {
    if (y + needed > 270) {
      addFooter(doc);
      doc.addPage();
      page++;
      addHeader(doc, page);
      y = MARGIN + 5;
    }
  };

  /* ── Page 1: Title ─────────────────────────────────────── */
  addHeader(doc, page);
  y = 30;

  doc.setFontSize(22);
  doc.setTextColor(20, 40, 80);
  doc.text('CRYORADAR', MARGIN, y);
  y += 8;

  doc.setFontSize(14);
  doc.setTextColor(60);
  doc.text('Technical Memo — Subsurface Analysis Report', MARGIN, y);
  y += 12;

  doc.setDrawColor(20, 100, 200);
  doc.setLineWidth(0.5);
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y);
  y += 10;

  /* ── Mission Summary ───────────────────────────────────── */
  doc.setFontSize(12);
  doc.setTextColor(20, 40, 80);
  doc.text('1. Mission Summary', MARGIN, y);
  y += 8;

  doc.setFontSize(9);
  doc.setTextColor(40);
  const summaryLines = [
    `Body: 🔴 Mars`,
    `Instrument: ${metadata.instrument}`,
    `Orbit: ${metadata.orbitNumber}`,
    `Date: ${metadata.acquisitionDate}`,
    `Region: ${metadata.region}`,
    `Center: ${metadata.centerLat.toFixed(2)}°N, ${metadata.centerLon.toFixed(2)}°E`,
    `Grid: ${dataset.radargram.width} traces × ${dataset.radargram.height} samples`,
  ];

  for (const line of summaryLines) {
    doc.text(line, MARGIN + 4, y);
    y += 5;
  }
  y += 5;

  doc.setFontSize(8);
  doc.setTextColor(80);
  const descLines = doc.splitTextToSize(metadata.description, CONTENT_WIDTH - 8);
  doc.text(descLines, MARGIN + 4, y);
  y += descLines.length * 4 + 8;

  /* ── Radargram Capture ─────────────────────────────────── */
  if (radargramImageDataUrl) {
    ensureSpace(70);
    doc.setFontSize(12);
    doc.setTextColor(20, 40, 80);
    doc.text('2. Radargram Cross-Section', MARGIN, y);
    y += 6;

    doc.addImage(radargramImageDataUrl, 'PNG', MARGIN, y, CONTENT_WIDTH, 55);
    y += 60;

    doc.setFontSize(7);
    doc.setTextColor(120);
    doc.text('Figure 1: Radargram cross-section with current colormap and contrast settings.', MARGIN, y);
    y += 8;
  }

  /* ── Anomaly Table ─────────────────────────────────────── */
  if (anomalies.length > 0) {
    ensureSpace(30);
    doc.setFontSize(12);
    doc.setTextColor(20, 40, 80);
    doc.text(`${radargramImageDataUrl ? '3' : '2'}. Detected Anomalies (${anomalies.length})`, MARGIN, y);
    y += 8;

    doc.setFontSize(7);
    doc.setTextColor(255, 255, 255);
    doc.setFillColor(30, 50, 90);
    doc.rect(MARGIN, y - 3, CONTENT_WIDTH, 5, 'F');
    const headers = ['#', 'Lat', 'Lon', 'Depth(m)', 'ε', 'P(Water)', 'P(Clay)', 'P(Clutter)', 'Dominant'];
    const colWidths = [8, 18, 18, 18, 12, 20, 18, 20, 30];
    let xPos = MARGIN + 1;
    for (let i = 0; i < headers.length; i++) {
      doc.text(headers[i], xPos, y);
      xPos += colWidths[i];
    }
    y += 5;

    doc.setTextColor(40);
    const maxRows = Math.min(anomalies.length, 25);
    for (let i = 0; i < maxRows; i++) {
      ensureSpace(5);
      const a = anomalies[i];
      if (i % 2 === 0) {
        doc.setFillColor(240, 245, 255);
        doc.rect(MARGIN, y - 3, CONTENT_WIDTH, 4, 'F');
      }
      xPos = MARGIN + 1;
      const cells = [
        `${i + 1}`,
        a.latitude.toFixed(2),
        a.longitude.toFixed(2),
        a.depthM.toFixed(1),
        a.apparentPermittivity.toFixed(1),
        `${(a.hypothesis.pLiquidWater * 100).toFixed(1)}%`,
        `${(a.hypothesis.pSmectiteClay * 100).toFixed(1)}%`,
        `${(a.hypothesis.pClutter * 100).toFixed(1)}%`,
        a.hypothesis.dominantHypothesis,
      ];
      for (let j = 0; j < cells.length; j++) {
        doc.text(cells[j], xPos, y);
        xPos += colWidths[j];
      }
      y += 4;
    }

    if (anomalies.length > 25) {
      doc.setTextColor(120);
      doc.text(`... and ${anomalies.length - 25} more anomalies.`, MARGIN + 4, y);
      y += 5;
    }
    y += 5;
  }

  /* ── UQ Results ────────────────────────────────────────── */
  if (uqResults && uqResults.length > 0) {
    ensureSpace(20);
    doc.setFontSize(12);
    doc.setTextColor(20, 40, 80);
    doc.text('4. Uncertainty Quantification (Monte Carlo)', MARGIN, y);
    y += 7;

    doc.setFontSize(8);
    doc.setTextColor(40);
    for (const uq of uqResults.slice(0, 10)) {
      ensureSpace(5);
      doc.text(
        `Anomaly ${uq.anomalyIndex + 1}: ${uq.meanDepthM.toFixed(1)}m ± ${uq.stdDevM.toFixed(1)}m (90% CI: ${uq.percentile5.toFixed(1)}–${uq.percentile95.toFixed(1)}m, N=${uq.nSamples})`,
        MARGIN + 4, y
      );
      y += 5;
    }
    y += 5;
  }

  /* ── PolSAR Summary ────────────────────────────────────── */
  if (polsarData) {
    ensureSpace(15);
    doc.setFontSize(12);
    doc.setTextColor(20, 40, 80);
    doc.text('5. PolSAR Decomposition Summary', MARGIN, y);
    y += 7;

    doc.setFontSize(8);
    doc.setTextColor(40);
    doc.text(`Grid: ${polsarData.width} × ${polsarData.height} pixels`, MARGIN + 4, y);
    y += 5;

    if (polsarData.pixels.length > 0) {
      const avgH = polsarData.pixels.reduce((s, p) => s + p.cloudePottier.entropy, 0) / polsarData.pixels.length;
      const avgA = polsarData.pixels.reduce((s, p) => s + p.cloudePottier.meanAlpha, 0) / polsarData.pixels.length;
      doc.text(`Mean Entropy: ${avgH.toFixed(3)}, Mean Alpha: ${(avgA * 180 / Math.PI).toFixed(1)}°`, MARGIN + 4, y);
      y += 5;
    }
    y += 5;
  }

  /* ── References ────────────────────────────────────────── */
  ensureSpace(20);
  doc.setFontSize(12);
  doc.setTextColor(20, 40, 80);
  doc.text('References', MARGIN, y);
  y += 7;

  doc.setFontSize(7);
  doc.setTextColor(60);
  for (const ref of metadata.references) {
    ensureSpace(5);
    const line = `${ref.authors} (${ref.year}). "${ref.title}." ${ref.journal}.${ref.doi ? ` doi:${ref.doi}` : ''}`;
    const wrapped = doc.splitTextToSize(line, CONTENT_WIDTH - 8);
    doc.text(wrapped, MARGIN + 4, y);
    y += wrapped.length * 3.5;
  }

  addFooter(doc);

  /* ── Download ──────────────────────────────────────────── */
  const filename = `CRYORADAR_TechMemo_Mars_${metadata.region.replace(/\s+/g, '_')}_${Date.now()}.pdf`;
  doc.save(filename);
}
