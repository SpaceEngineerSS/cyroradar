import { useCallback, useEffect } from 'react';
import { useCryoState, useCryoDispatch } from '../../context/CryoRadarContext';
import { generateTechnicalMemo } from '../../core/export/report-generator';
import type { AnomalyClass, AnomalyResult, DiscoveryEntry } from '../../types/types';

const STORAGE_KEY = 'cryoradar-discoveries';

const CLASS_ICONS: Record<AnomalyClass, string> = {
  'geological-interface': '🪨',
  'ice-deposit': '🧊',
  'wet-sediment': '💧',
  'liquid-water': '🌊',
};

const CLASS_COLORS: Record<AnomalyClass, string> = {
  'geological-interface': 'text-gray-400',
  'ice-deposit': 'text-ice-300',
  'wet-sediment': 'text-neon-orange',
  'liquid-water': 'text-neon-blue',
};

interface Achievement {
  id: string;
  title: string;
  icon: string;
  condition: (discoveries: DiscoveryEntry[]) => boolean;
}

const ACHIEVEMENTS: Achievement[] = [
  { id: 'first-scan', title: 'First Scan', icon: '🔍', condition: (d) => d.length >= 1 },
  { id: 'ice-hunter', title: 'Ice Hunter', icon: '🧊', condition: (d) => d.some(x => x.classification === 'ice-deposit') },
  { id: 'water-finder', title: 'Water Finder', icon: '🌊', condition: (d) => d.some(x => x.classification === 'liquid-water') },
  { id: 'deep-explorer', title: 'Deep Explorer', icon: '⛏️', condition: (d) => d.some(x => x.depthM > 1000) },
  { id: 'multi-region', title: 'Multi-Region', icon: '🗺️', condition: (d) => new Set(d.map(x => x.region)).size >= 3 },
  { id: 'prolific', title: 'Prolific Scientist', icon: '🏆', condition: (d) => d.length >= 10 },
];

function downloadFile(content: string, filename: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function anomaliesToCSV(anomalies: AnomalyResult[]): string {
  const header = '# Generated by CRYORADAR v7.0 - Chief Scientist & Architect: Mehmet Gümüş (github.com/SpaceEngineerSS)\n'
    + '# Export Date: ' + new Date().toISOString() + '\n'
    + '# Reference: Orosei et al. (2018), Science 361, 490-493\n'
    + 'Trace_Index,Sample_Index,Depth_Meters,Latitude,Longitude,Surface_Power_dB,Basal_Power_dB,Power_Ratio,Apparent_Dielectric,Classification,Confidence,Surface_Slope_Deg,Clutter_Warning,P_Water(%),P_Clay(%),P_Clutter(%),Dominant_Hypothesis\n';

  const rows = anomalies.map(a =>
    [
      a.traceIndex,
      a.sampleIndex,
      a.depthM.toFixed(1),
      a.latitude.toFixed(4),
      a.longitude.toFixed(4),
      a.surfacePower.toFixed(2),
      a.basalPower.toFixed(2),
      a.powerRatio.toFixed(4),
      a.apparentPermittivity.toFixed(2),
      a.classification,
      (a.confidence * 100).toFixed(1),
      a.surfaceSlopeDeg.toFixed(2),
      a.clutterWarning ? 'YES' : 'NO',
      (a.hypothesis.pLiquidWater * 100).toFixed(1),
      (a.hypothesis.pSmectiteClay * 100).toFixed(1),
      (a.hypothesis.pClutter * 100).toFixed(1),
      a.hypothesis.dominantHypothesis,
    ].join(',')
  );

  return header + rows.join('\n') + '\n';
}

function anomaliesToJSON(anomalies: AnomalyResult[]): string {
  const exportData = {
    metadata: {
      generator: 'CRYORADAR',
      developer: 'Mehmet Gümüş (github.com/SpaceEngineerSS)',
      exportDate: new Date().toISOString(),
      reference: 'Orosei et al. (2018), Science 361, 490-493; Bierson et al. (2021), GRL 48',
      totalAnomalies: anomalies.length,
    },
    anomalies: anomalies.map(a => ({
      traceIndex: a.traceIndex,
      sampleIndex: a.sampleIndex,
      depthMeters: a.depthM,
      latitude: a.latitude,
      longitude: a.longitude,
      surfacePowerDb: a.surfacePower,
      basalPowerDb: a.basalPower,
      powerRatio: a.powerRatio,
      apparentDielectric: a.apparentPermittivity,
      classification: a.classification,
      confidence: a.confidence,
      surfaceSlopeDeg: a.surfaceSlopeDeg,
      clutterWarning: a.clutterWarning,
      hypothesis: {
        pWater: a.hypothesis.pLiquidWater,
        pClay: a.hypothesis.pSmectiteClay,
        pClutter: a.hypothesis.pClutter,
        dominant: a.hypothesis.dominantHypothesis,
      },
    })),
  };
  return JSON.stringify(exportData, null, 2);
}

export function DiscoveryLog() {
  const { discoveries, anomalies, dataset, uqResults, polsarData } = useCryoState();
  const dispatch = useCryoDispatch();

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored) {
        const parsed: DiscoveryEntry[] = JSON.parse(stored);
        for (const entry of parsed) {
          dispatch({ type: 'ADD_DISCOVERY', discovery: entry });
        }
      }
    } catch { /* ignore parse errors */ }
  }, [dispatch]);

  useEffect(() => {
    if (discoveries.length > 0) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(discoveries));
    }
  }, [discoveries]);

  const exportCSV = useCallback(() => {
    if (anomalies.length === 0) return;
    const csv = anomaliesToCSV(anomalies);
    downloadFile(csv, `cryoradar-anomalies-${Date.now()}.csv`, 'text/csv');
  }, [anomalies]);

  const exportJSON = useCallback(() => {
    if (anomalies.length === 0) return;
    const json = anomaliesToJSON(anomalies);
    downloadFile(json, `cryoradar-anomalies-${Date.now()}.json`, 'application/json');
  }, [anomalies]);

  const clearAll = useCallback(() => {
    dispatch({ type: 'CLEAR_DISCOVERIES' });
    localStorage.removeItem(STORAGE_KEY);
  }, [dispatch]);

  const unlockedAchievements = ACHIEVEMENTS.filter(a => a.condition(discoveries));

  return (
    <div className="p-3 space-y-4">
      <h3 className="text-xs font-semibold uppercase tracking-wider text-gray-500 font-mono">
        Discovery Log
      </h3>

      {unlockedAchievements.length > 0 && (
        <div className="space-y-2">
          <h4 className="text-[10px] font-semibold uppercase text-gray-500 font-mono">Achievements</h4>
          <div className="flex flex-wrap gap-1.5">
            {ACHIEVEMENTS.map(a => {
              const unlocked = a.condition(discoveries);
              return (
                <div
                  key={a.id}
                  className={`flex items-center gap-1 px-2 py-1 rounded-full text-[10px] font-mono border transition-all ${
                    unlocked
                      ? 'bg-neon-purple/10 border-neon-purple/30 text-neon-purple'
                      : 'bg-space-850 border-space-700 text-gray-600 opacity-50'
                  }`}
                  title={unlocked ? `Unlocked: ${a.title}` : `Locked: ${a.title}`}
                >
                  <span>{a.icon}</span>
                  <span>{a.title}</span>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {anomalies.length > 0 && (
        <div className="p-2 rounded-lg bg-space-850 border border-space-700">
          <h4 className="text-[10px] font-semibold uppercase text-gray-500 font-mono mb-2">
            Scientific Export ({anomalies.length} anomalies)
          </h4>
          <div className="flex gap-1.5">
            <button
              id="export-csv-btn"
              onClick={exportCSV}
              className="px-2.5 py-1.5 text-[10px] font-mono font-medium rounded bg-emerald-500/10 border border-emerald-500/30 text-emerald-400 hover:bg-emerald-500/20 transition-all"
            >
              📊 Export CSV
            </button>
            <button
              id="export-json-btn"
              onClick={exportJSON}
              className="px-2.5 py-1.5 text-[10px] font-mono font-medium rounded bg-neon-cyan/10 border border-neon-cyan/30 text-neon-cyan hover:bg-neon-cyan/20 transition-all"
            >
              📋 Export JSON
            </button>
            <button
              id="export-pdf-btn"
              onClick={() => {
                if (!dataset || anomalies.length === 0) return;
                generateTechnicalMemo({
                  dataset,
                  anomalies,
                  uqResults: uqResults.length > 0 ? uqResults : undefined,
                  polsarData,
                });
              }}
              className="px-2.5 py-1.5 text-[10px] font-mono font-medium rounded bg-purple-500/10 border border-purple-500/30 text-purple-400 hover:bg-purple-500/20 transition-all"
            >
              📄 Export PDF
            </button>
          </div>
        </div>
      )}

      <div className="flex items-center justify-between">
        <span className="text-[11px] font-mono text-gray-400">{discoveries.length} discoveries</span>
        <div className="flex gap-1.5">
          {discoveries.length > 0 && (
            <button
              onClick={clearAll}
              className="px-2 py-1 text-[10px] font-mono rounded bg-neon-red/10 border border-neon-red/30 text-neon-red hover:bg-neon-red/20 transition-all"
            >
              Clear Log
            </button>
          )}
        </div>
      </div>

      {discoveries.length === 0 ? (
        <div className="flex flex-col items-center justify-center h-32 gap-3 text-gray-600">
          <span className="text-3xl">📋</span>
          <p className="text-xs text-center">No discoveries yet. Run auto-detection<br />and log findings to build your record.</p>
        </div>
      ) : (
        <div className="space-y-1 max-h-[400px] overflow-y-auto">
          {discoveries.map(d => (
            <div
              key={d.id}
              className="p-2 rounded-lg bg-space-850 border border-space-700 hover:border-space-600 transition-colors"
            >
              <div className="flex items-center gap-2 mb-1">
                <span className="text-sm">{CLASS_ICONS[d.classification]}</span>
                <span className={`text-[11px] font-semibold font-mono ${CLASS_COLORS[d.classification]}`}>
                  {d.classification.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase())}
                </span>
                <span className="ml-auto text-[9px] font-mono text-gray-600">
                  {new Date(d.timestamp).toLocaleDateString()}
                </span>
              </div>
              <div className="grid grid-cols-2 gap-x-4 gap-y-0.5 text-[10px] font-mono text-gray-500">
                <span>ε = {d.apparentPermittivity.toFixed(2)}</span>
                <span>Depth: {d.depthM} m</span>
                <span>{d.latitude.toFixed(3)}°N</span>
                <span>{d.longitude.toFixed(3)}°E</span>
                <span>Trace #{d.traceIndex}</span>
                <span>Confidence: {(d.confidence * 100).toFixed(0)}%</span>
                <span className="col-span-2 text-gray-600">{d.region}</span>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
